CREATE TABLE historique_revision_demande_espace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id BIGINT NOT NULL REFERENCES demande_espace(id) ON DELETE CASCADE,
    acteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    action VARCHAR(32) NOT NULL CHECK (action IN ('CORRECTION', 'REEXAMEN')),
    motif VARCHAR(1000) NOT NULL,
    date_action TIMESTAMPTZ NOT NULL DEFAULT now()
);
