-- Checkout attempts hold capacity until Stripe confirms or expires the session.
-- A paid registration is inserted only after a signed paid webhook.
CREATE TABLE reservation_payante_activite (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activite_id BIGINT NOT NULL REFERENCES activite(id),
  utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
  demande UUID NOT NULL,
  quantite INTEGER NOT NULL CHECK (quantite BETWEEN 1 AND 4),
  prenom VARCHAR(80) NOT NULL,
  nom VARCHAR(80) NOT NULL,
  email VARCHAR(254) NOT NULL,
  telephone VARCHAR(30) NOT NULL DEFAULT '',
  montant_centimes BIGINT NOT NULL CHECK (montant_centimes > 0),
  commission_centimes BIGINT NOT NULL CHECK (commission_centimes >= 0 AND commission_centimes < montant_centimes),
  compte_stripe VARCHAR(100) NOT NULL,
  session_stripe VARCHAR(255) UNIQUE,
  paiement_stripe VARCHAR(255),
  remboursement_stripe VARCHAR(255),
  inscription_id BIGINT UNIQUE REFERENCES inscription_activite(id),
  statut VARCHAR(30) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN
    ('EN_ATTENTE','PAYE','EXPIRE','ECHOUE','REMBOURSEMENT_EN_COURS','REMBOURSE')),
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  date_paiement TIMESTAMPTZ,
  UNIQUE(utilisateur_id,demande)
);
CREATE INDEX reservation_payante_activite_places ON reservation_payante_activite(activite_id,statut);
CREATE INDEX reservation_payante_activite_utilisateur ON reservation_payante_activite(utilisateur_id,date_creation DESC);
