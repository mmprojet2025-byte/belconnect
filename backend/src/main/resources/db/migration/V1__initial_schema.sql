CREATE TABLE utilisateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    nom VARCHAR(150) NOT NULL,
    statut VARCHAR(32) NOT NULL DEFAULT 'ACTIF',
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT utilisateur_email_normalise CHECK (email = lower(email)),
    CONSTRAINT utilisateur_statut_valide CHECK (statut IN ('ACTIF', 'SUSPENDU', 'DESACTIVE'))
);

CREATE UNIQUE INDEX utilisateur_email_unique ON utilisateur (lower(email));

CREATE TABLE espace_organisateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(180) NOT NULL,
    type VARCHAR(32) NOT NULL,
    statut VARCHAR(32) NOT NULL DEFAULT 'ACTIF',
    createur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    CONSTRAINT espace_type_valide CHECK (type IN ('ASSOCIATION', 'PARTICULIER', 'ORGANISATEUR')),
    CONSTRAINT espace_statut_valide CHECK (statut IN ('ACTIF', 'SUSPENDU', 'FERME'))
);

CREATE TABLE appartenance_espace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
    role VARCHAR(24) NOT NULL,
    statut VARCHAR(32) NOT NULL DEFAULT 'ACTIF',
    CONSTRAINT appartenance_unique UNIQUE (utilisateur_id, espace_id),
    CONSTRAINT appartenance_role_valide CHECK (role IN ('ADMINISTRATEUR', 'MEMBRE')),
    CONSTRAINT appartenance_statut_valide CHECK (statut IN ('ACTIF', 'SUSPENDU', 'RETIRE'))
);

CREATE INDEX appartenance_espace_index ON appartenance_espace (espace_id);

CREATE TABLE groupe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
    nom VARCHAR(150) NOT NULL,
    description TEXT,
    adhesion_ouverte BOOLEAN NOT NULL DEFAULT false,
    statut VARCHAR(32) NOT NULL DEFAULT 'ACTIF',
    CONSTRAINT groupe_espace_id_unique UNIQUE (id, espace_id),
    CONSTRAINT groupe_nom_unique UNIQUE (espace_id, nom),
    CONSTRAINT groupe_statut_valide CHECK (statut IN ('ACTIF', 'SUSPENDU', 'ARCHIVE'))
);

CREATE TABLE projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
    groupe_id BIGINT,
    auteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    titre VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    objectif TEXT NOT NULL,
    statut VARCHAR(32) NOT NULL DEFAULT 'BROUILLON',
    visibilite VARCHAR(24) NOT NULL DEFAULT 'PUBLIQUE',
    debut_prevu DATE,
    fin_prevue DATE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_modification TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT projet_groupe_meme_espace FOREIGN KEY (groupe_id, espace_id)
        REFERENCES groupe(id, espace_id),
    CONSTRAINT projet_titre_longueur CHECK (char_length(trim(titre)) BETWEEN 5 AND 180),
    CONSTRAINT projet_statut_valide CHECK (statut IN ('BROUILLON', 'SOUMIS', 'A_CORRIGER', 'APPROUVE', 'REFUSE')),
    CONSTRAINT projet_visibilite_valide CHECK (visibilite IN ('PUBLIQUE', 'GROUPE')),
    CONSTRAINT projet_dates_valides CHECK (fin_prevue IS NULL OR debut_prevu IS NULL OR fin_prevue >= debut_prevu),
    CONSTRAINT projet_visibilite_groupe CHECK (visibilite <> 'GROUPE' OR groupe_id IS NOT NULL)
);

CREATE INDEX projet_espace_statut_index ON projet (espace_id, statut);
CREATE INDEX projet_auteur_index ON projet (auteur_id);
CREATE INDEX projet_groupe_index ON projet (groupe_id);

CREATE TABLE validation_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id BIGINT NOT NULL REFERENCES projet(id),
    examinateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    decision VARCHAR(32) NOT NULL,
    commentaire TEXT,
    date_decision TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT validation_decision_valide CHECK (decision IN ('APPROUVE', 'REFUSE', 'A_CORRIGER', 'AVIS_FAVORABLE')),
    CONSTRAINT validation_motif_requis CHECK (decision NOT IN ('REFUSE', 'A_CORRIGER') OR nullif(trim(commentaire), '') IS NOT NULL)
);

CREATE INDEX validation_projet_index ON validation_projet (projet_id, date_decision);

CREATE TABLE participation_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id BIGINT NOT NULL REFERENCES projet(id),
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    type_aide VARCHAR(32) NOT NULL,
    statut VARCHAR(32) NOT NULL DEFAULT 'PROPOSEE',
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT participation_type_valide CHECK (type_aide IN ('BENEVOLAT', 'COMPETENCES', 'PARTAGE', 'SOUTIEN_MORAL')),
    CONSTRAINT participation_statut_valide CHECK (statut IN ('PROPOSEE', 'ACCEPTEE', 'REFUSEE', 'ANNULEE'))
);

CREATE UNIQUE INDEX participation_active_unique
    ON participation_projet (projet_id, utilisateur_id, type_aide)
    WHERE statut IN ('PROPOSEE', 'ACCEPTEE');

