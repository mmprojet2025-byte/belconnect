CREATE TABLE commentaire_activite (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activite_id BIGINT NOT NULL REFERENCES activite(id) ON DELETE CASCADE,
  auteur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  contenu VARCHAR(500) NOT NULL CHECK (length(trim(contenu)) BETWEEN 1 AND 500),
  demande UUID NOT NULL,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT commentaire_activite_demande_unique UNIQUE(auteur_id, demande)
);
CREATE INDEX commentaire_activite_fil ON commentaire_activite(activite_id, id DESC);
