ALTER TABLE activite
    ADD COLUMN espace_id BIGINT REFERENCES espace_organisateur(id),
    ADD COLUMN groupe_id BIGINT REFERENCES groupe(id),
    ADD COLUMN createur_id BIGINT REFERENCES utilisateur(id),
    ADD COLUMN creation_request UUID,
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN visibilite VARCHAR(16) NOT NULL DEFAULT 'PUBLIQUE' CHECK (visibilite IN ('PUBLIQUE','PRIVEE')),
    ADD COLUMN cloture_inscriptions TIMESTAMPTZ,
    ADD CONSTRAINT activite_cloture CHECK (cloture_inscriptions IS NULL OR cloture_inscriptions <= debut),
    ADD CONSTRAINT activite_creation_unique UNIQUE(createur_id,creation_request),
    ADD CONSTRAINT activite_groupe_espace CHECK (groupe_id IS NULL OR espace_id IS NOT NULL);
CREATE TABLE historique_gestion_activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activite_id BIGINT NOT NULL REFERENCES activite(id),
    acteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    action VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL,
    date_action TIMESTAMPTZ NOT NULL DEFAULT now()
);
