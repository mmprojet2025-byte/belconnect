CREATE TABLE notification_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    projet_id BIGINT NOT NULL REFERENCES projet(id),
    evenement VARCHAR(20) NOT NULL CHECK (evenement IN ('RETIRE', 'TERMINE')),
    version_projet BIGINT NOT NULL,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_lecture TIMESTAMPTZ,
    UNIQUE (utilisateur_id, projet_id, evenement, version_projet)
);
CREATE INDEX notification_projet_utilisateur ON notification_projet(utilisateur_id, date_creation DESC);
