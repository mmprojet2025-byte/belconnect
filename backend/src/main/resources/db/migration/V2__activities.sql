-- One dated activity per catalogue entry. Booking remains a frontend simulation.
CREATE TABLE activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    titre VARCHAR(250) NOT NULL CHECK (length(trim(titre)) > 0),
    categorie VARCHAR(32) NOT NULL CHECK (categorie IN ('art','gastronomie','nature','culture','savoir-faire','bien-etre')),
    ville VARCHAR(120) NOT NULL,
    lieu VARCHAR(250) NOT NULL,
    organisateur_nom VARCHAR(180) NOT NULL,
    prix NUMERIC(10,2) NOT NULL CHECK (prix >= 0),
    image VARCHAR(100) NOT NULL CHECK (image ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    debut TIMESTAMPTZ NOT NULL,
    description TEXT NOT NULL,
    badge VARCHAR(80),
    duree VARCHAR(80) NOT NULL,
    capacite INTEGER NOT NULL CHECK (capacite > 0),
    places_disponibles INTEGER NOT NULL CHECK (places_disponibles >= 0 AND places_disponibles <= capacite),
    public_cible VARCHAR(200) NOT NULL,
    rendez_vous VARCHAR(250) NOT NULL,
    programme TEXT[] NOT NULL DEFAULT '{}',
    inclus TEXT[] NOT NULL DEFAULT '{}',
    preparation TEXT NOT NULL,
    demonstration BOOLEAN NOT NULL DEFAULT false,
    publiee BOOLEAN NOT NULL DEFAULT false,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX activite_publique_date ON activite (debut, id) WHERE publiee;
