CREATE TABLE demande_intervention_membre (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
 groupe_id BIGINT REFERENCES groupe(id),
 cible_id BIGINT NOT NULL REFERENCES utilisateur(id),
 demandeur_id BIGINT NOT NULL REFERENCES utilisateur(id),
 motif VARCHAR(1000) NOT NULL,
 statut VARCHAR(16) NOT NULL DEFAULT 'EN_ATTENTE' CHECK(statut IN ('EN_ATTENTE','APPROUVEE','REFUSEE')),
 decideur_id BIGINT REFERENCES utilisateur(id),
 motif_decision VARCHAR(1000),
 cree_le TIMESTAMPTZ NOT NULL DEFAULT now(),
 decide_le TIMESTAMPTZ
);
CREATE UNIQUE INDEX intervention_pending_unique ON demande_intervention_membre(espace_id,COALESCE(groupe_id,0),cible_id) WHERE statut='EN_ATTENTE';
