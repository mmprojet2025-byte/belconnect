CREATE TABLE notification_adhesion_groupe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    demande_id BIGINT NOT NULL REFERENCES demande_adhesion_groupe(id) ON DELETE CASCADE,
    evenement VARCHAR(24) NOT NULL CHECK (evenement IN ('DEMANDE_RECUE', 'DEMANDE_ACCEPTEE', 'DEMANDE_REFUSEE')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_lecture TIMESTAMPTZ,
    UNIQUE (utilisateur_id, demande_id, evenement)
);
CREATE INDEX idx_notification_adhesion_groupe_non_lue
    ON notification_adhesion_groupe(utilisateur_id, date_creation DESC) WHERE date_lecture IS NULL;
