ALTER TABLE projet ADD COLUMN etape_validation VARCHAR(24)
    CHECK (etape_validation IN ('REFERENT', 'ADMINISTRATEUR'));
ALTER TABLE projet ADD COLUMN date_soumission TIMESTAMPTZ;
CREATE TABLE soumission_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id BIGINT NOT NULL REFERENCES projet(id),
    auteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    version_brouillon BIGINT NOT NULL,
    destination VARCHAR(24) NOT NULL CHECK (destination IN ('REFERENT', 'ADMINISTRATEUR')),
    date_soumission TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (projet_id, version_brouillon)
);
CREATE INDEX projet_validation_attente ON projet(espace_id, etape_validation) WHERE statut='SOUMIS';
