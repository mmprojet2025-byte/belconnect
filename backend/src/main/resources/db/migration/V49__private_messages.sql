CREATE TABLE conversation_privee (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  groupe_id BIGINT REFERENCES groupe(id) ON DELETE SET NULL,
  participant_a_id BIGINT NOT NULL REFERENCES utilisateur(id),
  participant_b_id BIGINT NOT NULL REFERENCES utilisateur(id),
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT conversation_privee_ordre CHECK (participant_a_id < participant_b_id),
  CONSTRAINT conversation_privee_unique UNIQUE(groupe_id, participant_a_id, participant_b_id)
);
CREATE INDEX conversation_privee_participant_b ON conversation_privee(participant_b_id, id DESC);

CREATE TABLE message_prive (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES conversation_privee(id) ON DELETE CASCADE,
  expediteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
  contenu VARCHAR(2000) NOT NULL CHECK (length(trim(contenu)) BETWEEN 1 AND 2000),
  demande UUID NOT NULL,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  date_lecture TIMESTAMPTZ,
  CONSTRAINT message_prive_demande_unique UNIQUE(expediteur_id, demande)
);
CREATE INDEX message_prive_fil ON message_prive(conversation_id, id DESC);
CREATE INDEX message_prive_non_lu ON message_prive(conversation_id, expediteur_id) WHERE date_lecture IS NULL;

CREATE TABLE blocage_message_prive (
  bloqueur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  bloque_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (bloqueur_id, bloque_id),
  CONSTRAINT blocage_message_prive_soi_meme CHECK (bloqueur_id <> bloque_id)
);

CREATE TABLE signalement_message_prive (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES message_prive(id) ON DELETE CASCADE,
  auteur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  motif VARCHAR(500) NOT NULL CHECK (length(trim(motif)) BETWEEN 1 AND 500),
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT signalement_message_prive_unique UNIQUE(message_id, auteur_id)
);
