CREATE TABLE message_groupe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  groupe_id BIGINT NOT NULL REFERENCES groupe(id) ON DELETE CASCADE,
  expediteur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  contenu VARCHAR(2000) NOT NULL CHECK (length(trim(contenu)) BETWEEN 1 AND 2000),
  demande UUID NOT NULL,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (expediteur_id, demande)
);
CREATE INDEX message_groupe_fil ON message_groupe(groupe_id, id DESC);

CREATE TABLE lecture_message_groupe (
  groupe_id BIGINT NOT NULL REFERENCES groupe(id) ON DELETE CASCADE,
  utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
  dernier_message_id BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (groupe_id, utilisateur_id)
);
