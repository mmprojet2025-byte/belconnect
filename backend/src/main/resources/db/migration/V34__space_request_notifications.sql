CREATE TABLE notification_demande_espace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    demande_id BIGINT NOT NULL REFERENCES demande_espace(id) ON DELETE CASCADE,
    evenement VARCHAR(24) NOT NULL CHECK (evenement IN ('DEMANDE_RECUE', 'DEMANDE_APPROUVEE', 'DEMANDE_REFUSEE')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_lecture TIMESTAMPTZ,
    UNIQUE (utilisateur_id, demande_id, evenement)
);
CREATE INDEX idx_notification_demande_espace_non_lue ON notification_demande_espace(utilisateur_id, date_creation DESC) WHERE date_lecture IS NULL;
