CREATE TABLE notification_activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    inscription_id BIGINT NOT NULL UNIQUE REFERENCES inscription_activite(id),
    activite_id BIGINT NOT NULL REFERENCES activite(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_lecture TIMESTAMPTZ
);
CREATE INDEX notification_activite_utilisateur ON notification_activite(utilisateur_id, date_creation DESC);
