CREATE TABLE offre_participation_projet (
 projet_id BIGINT PRIMARY KEY REFERENCES projet(id),
 description VARCHAR(500) NOT NULL CHECK (length(trim(description)) BETWEEN 10 AND 500),
 prix_centimes BIGINT NOT NULL CHECK (prix_centimes BETWEEN 100 AND 10000000),
 capacite INTEGER NOT NULL CHECK (capacite BETWEEN 1 AND 100000),
 active BOOLEAN NOT NULL DEFAULT true,
 date_modification TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE inscription_payante_projet (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 projet_id BIGINT NOT NULL REFERENCES offre_participation_projet(projet_id),
 participant_id BIGINT NOT NULL REFERENCES utilisateur(id),
 demande UUID NOT NULL,
 prix_centimes BIGINT NOT NULL CHECK (prix_centimes BETWEEN 100 AND 10000000),
 commission_centimes BIGINT NOT NULL CHECK (commission_centimes >= 0 AND commission_centimes < prix_centimes),
 compte_stripe VARCHAR(100) NOT NULL,
 session_stripe VARCHAR(255) UNIQUE,
 paiement_stripe VARCHAR(255),
 statut VARCHAR(30) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE','PAYE','EXPIRE','ECHOUE','REMBOURSEMENT_EN_COURS','REMBOURSE')),
 expiration TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '30 minutes'),
 date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
 date_paiement TIMESTAMPTZ,
 UNIQUE (participant_id, demande)
);
CREATE INDEX inscription_payante_projet_places ON inscription_payante_projet(projet_id,statut,expiration);
CREATE INDEX inscription_payante_projet_participant ON inscription_payante_projet(participant_id,date_creation DESC);
