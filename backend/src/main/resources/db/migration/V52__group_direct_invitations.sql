CREATE TABLE invitation_groupe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  groupe_id BIGINT NOT NULL REFERENCES groupe(id),
  invite_id BIGINT NOT NULL REFERENCES utilisateur(id),
  inviter_id BIGINT NOT NULL REFERENCES utilisateur(id),
  statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE','ACCEPTEE','REFUSEE')),
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  date_decision TIMESTAMPTZ,
  date_lecture TIMESTAMPTZ,
  UNIQUE (groupe_id,invite_id)
);
CREATE INDEX invitation_groupe_invite_idx ON invitation_groupe(invite_id,date_creation DESC);
