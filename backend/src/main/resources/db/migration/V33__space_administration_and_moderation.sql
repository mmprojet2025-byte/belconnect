ALTER TABLE historique_gestion_espace ADD COLUMN motif TEXT NOT NULL DEFAULT '';

ALTER TABLE activite ADD COLUMN masquee_moderation BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE projet ADD COLUMN masque_moderation BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE moderation_plateforme (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
  activite_id BIGINT REFERENCES activite(id),
  projet_id BIGINT REFERENCES projet(id),
  acteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
  action VARCHAR(32) NOT NULL CHECK (action IN ('MASQUER','RETABLIR','SUSPENDRE_ESPACE','REACTIVER_ESPACE')),
  motif TEXT NOT NULL CHECK (length(trim(motif)) BETWEEN 10 AND 1000),
  date_action TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((action IN ('SUSPENDRE_ESPACE','REACTIVER_ESPACE') AND activite_id IS NULL AND projet_id IS NULL)
    OR (action IN ('MASQUER','RETABLIR') AND ((activite_id IS NULL) <> (projet_id IS NULL))))
);
CREATE INDEX moderation_plateforme_espace_date ON moderation_plateforme(espace_id,date_action DESC);
