ALTER TABLE offre_participation_projet
  ADD CONSTRAINT offre_participation_projet_prix_centimes_check
  CHECK (prix_centimes = 0 OR prix_centimes BETWEEN 100 AND 10000000);

CREATE TABLE inscription_gratuite_projet (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projet_id BIGINT NOT NULL REFERENCES offre_participation_projet(projet_id),
  participant_id BIGINT NOT NULL REFERENCES utilisateur(id),
  statut VARCHAR(20) NOT NULL DEFAULT 'CONFIRMEE' CHECK (statut IN ('CONFIRMEE','ANNULEE')),
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  date_annulation TIMESTAMPTZ,
  UNIQUE (projet_id,participant_id)
);
CREATE INDEX inscription_gratuite_projet_participant ON inscription_gratuite_projet(participant_id,date_creation DESC);
