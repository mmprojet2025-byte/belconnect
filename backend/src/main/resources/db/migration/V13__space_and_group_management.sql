CREATE TABLE demande_espace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demandeur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    creation_request UUID NOT NULL,
    nom VARCHAR(180) NOT NULL,
    type VARCHAR(32) NOT NULL CHECK (type IN ('ASSOCIATION','PARTICULIER','ORGANISATEUR')),
    description TEXT NOT NULL DEFAULT '',
    statut VARCHAR(24) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE','APPROUVEE','REFUSEE')),
    version BIGINT NOT NULL DEFAULT 0,
    espace_id BIGINT REFERENCES espace_organisateur(id),
    examinateur_id BIGINT REFERENCES utilisateur(id),
    motif TEXT NOT NULL DEFAULT '',
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_decision TIMESTAMPTZ,
    UNIQUE(demandeur_id, creation_request),
    CHECK ((statut='EN_ATTENTE' AND examinateur_id IS NULL AND date_decision IS NULL AND espace_id IS NULL)
        OR (statut='APPROUVEE' AND examinateur_id IS NOT NULL AND date_decision IS NOT NULL AND espace_id IS NOT NULL)
        OR (statut='REFUSEE' AND examinateur_id IS NOT NULL AND date_decision IS NOT NULL AND espace_id IS NULL AND length(trim(motif))>0))
);

CREATE TABLE historique_gestion_espace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espace_id BIGINT NOT NULL REFERENCES espace_organisateur(id),
    groupe_id BIGINT REFERENCES groupe(id),
    acteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    action VARCHAR(40) NOT NULL,
    version BIGINT NOT NULL,
    date_action TIMESTAMPTZ NOT NULL DEFAULT now()
);
