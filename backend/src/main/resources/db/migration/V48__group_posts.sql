CREATE TABLE publication_groupe_mobile (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  groupe_id BIGINT NOT NULL REFERENCES groupe(id) ON DELETE CASCADE,
  auteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
  contenu VARCHAR(1000) NOT NULL CHECK (length(trim(contenu)) BETWEEN 1 AND 1000),
  demande UUID NOT NULL,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT publication_groupe_mobile_demande_unique UNIQUE(auteur_id, demande)
);
CREATE INDEX publication_groupe_mobile_fil ON publication_groupe_mobile(groupe_id, id DESC);
