CREATE TABLE don_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projet_id BIGINT NOT NULL REFERENCES projet(id),
    donateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    demande UUID NOT NULL,
    montant_centimes BIGINT NOT NULL CHECK (montant_centimes BETWEEN 100 AND 10000000),
    commission_centimes BIGINT NOT NULL CHECK (commission_centimes >= 0 AND commission_centimes < montant_centimes),
    devise VARCHAR(3) NOT NULL DEFAULT 'eur' CHECK (devise = 'eur'),
    compte_stripe VARCHAR(100) NOT NULL CHECK (compte_stripe ~ '^acct_[A-Za-z0-9]+$'),
    session_stripe VARCHAR(255) UNIQUE,
    paiement_stripe VARCHAR(255),
    statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE' CHECK (statut IN ('EN_ATTENTE','PAYE','ECHOUE','EXPIRE','REMBOURSE')),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_paiement TIMESTAMPTZ,
    CONSTRAINT don_projet_demande_unique UNIQUE (donateur_id, demande),
    CONSTRAINT don_projet_paye_coherent CHECK (statut <> 'PAYE' OR date_paiement IS NOT NULL)
);

CREATE INDEX don_projet_donateur_index ON don_projet(donateur_id,date_creation DESC);
CREATE INDEX don_projet_projet_index ON don_projet(projet_id,statut);
