CREATE TABLE demande_adhesion_groupe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id),
    groupe_id BIGINT NOT NULL,
    espace_id BIGINT NOT NULL,
    statut VARCHAR(24) NOT NULL CHECK (statut IN ('EN_ATTENTE','ACCEPTEE','REFUSEE')),
    version BIGINT NOT NULL DEFAULT 0,
    motif TEXT NOT NULL DEFAULT '',
    examinateur_id BIGINT REFERENCES utilisateur(id),
    date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
    date_decision TIMESTAMPTZ,
    UNIQUE(utilisateur_id,groupe_id),
    FOREIGN KEY (groupe_id,espace_id) REFERENCES groupe(id,espace_id),
    CHECK (statut<>'REFUSEE' OR length(trim(motif))>0)
);
CREATE INDEX demande_adhesion_espace_statut ON demande_adhesion_groupe(espace_id,statut);
