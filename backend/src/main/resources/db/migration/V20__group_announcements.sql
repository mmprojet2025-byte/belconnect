CREATE TABLE annonce_groupe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  groupe_id BIGINT NOT NULL REFERENCES groupe(id),
  auteur_id BIGINT NOT NULL REFERENCES utilisateur(id),
  contenu VARCHAR(1000) NOT NULL CHECK (length(trim(contenu)) BETWEEN 1 AND 1000),
  demande UUID NOT NULL,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT annonce_groupe_demande_unique UNIQUE(auteur_id,demande)
);
CREATE INDEX annonce_groupe_fil ON annonce_groupe(groupe_id,date_creation DESC,id DESC);
